// ---- helpers -------------------------------------------------------------
// Keep all "reach into the data" logic here so pages/components stay dumb.

export function getNewsById(id: number): NewsItem | undefined {
  return news.find((item) => item.id === id)
}

export function getNewsByCategory(category: Category): NewsItem[] {
  return news.filter((item) => item.category === category)
}

/** Latest items, optionally excluding one article (e.g. the one you're on). */
export function getLatest(excludeId?: number, limit = 6): NewsItem[] {
  return news.filter((item) => item.id !== excludeId).slice(0, limit)
}

/** Fills a category grid up to `limit` items, padding with other categories' news if needed. */
export function getCategoryPreview(category: Category, limit = 3): NewsItem[] {
  const own = getNewsByCategory(category)
  const rest = news.filter((item) => item.category !== category)
  return own.concat(rest).slice(0, limit)
}
